def _canonical_json_bytes(value: object) -> bytes:
    return json.dumps(
        value,
        allow_nan=False,
        ensure_ascii=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")


def _sha256(value: bytes | str) -> str:
    payload = value.encode("utf-8") if isinstance(value, str) else value
    return hashlib.sha256(payload).hexdigest()


def _runner_sha256() -> str:
    return _sha256(Path(__file__).read_bytes())


def _jsonable(value: object) -> object:
    if isinstance(value, Enum):
        return value.value
    if isinstance(value, Mapping):
        return {
            str(key): _jsonable(item)
            for key, item in sorted(value.items(), key=lambda pair: str(pair[0]))
        }
    if isinstance(value, (tuple, list)):
        return [_jsonable(item) for item in value]
    if hasattr(value, "__dataclass_fields__"):
        return _jsonable(asdict(cast(Any, value)))
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    raise TypeError(f"value is not canonically JSON serializable: {type(value)!r}")


class _FramedHash:
    """Length-frame one domain and every canonical JSON record."""

    __slots__ = ("_hasher",)

    def __init__(self, domain: bytes) -> None:
        self._hasher = hashlib.sha256()
        self._hasher.update(struct.pack(">Q", len(domain)))
        self._hasher.update(domain)

    def add(self, record: Mapping[str, object]) -> None:
        payload = _canonical_json_bytes(_jsonable(dict(record)))
        self._hasher.update(struct.pack(">Q", len(payload)))
        self._hasher.update(payload)

    def hexdigest(self) -> str:
        return self._hasher.hexdigest()


def _as_mapping(value: object, name: str) -> dict[str, object]:
    if not isinstance(value, dict) or not all(isinstance(key, str) for key in value):
        raise ValueError(f"{name} must be a JSON object with string keys")
    return cast(dict[str, object], value)


def _as_sequence(value: object, name: str) -> list[object]:
    if not isinstance(value, list):
        raise ValueError(f"{name} must be a JSON array")
    return cast(list[object], value)


def _as_text(value: object, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} must be nonempty text")
    return value


def _as_int(value: object, name: str, *, minimum: int = 0) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise ValueError(f"{name} must be an integer >= {minimum}")
    return value


def _as_float(value: object, name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{name} must be numeric")
    result = float(value)
    if not 0.0 <= result <= 1.0:
        raise ValueError(f"{name} must be in [0, 1]")
    return result


@dataclass(frozen=True, slots=True)
class EventWeight:
    kind: str
    weight: int


@dataclass(frozen=True, slots=True)
class DifferentialConfig:
    schema_version: str
    generator_version: str
    prng: str
    seed: int
    committed_events: int
    committed_events_per_stream: int
    max_proposals_per_stream: int
    short_prefix_committed_events: int
    claim_count: int
    document_slots: int
    bootstrap_document_slots: int
    chunks_per_document: int
    family_slots: int
    bootstrap_family_slots: int
    max_active_groups: int
    requirement_count_choices: tuple[int, ...]
    text_pool: tuple[str, ...]
    score_profiles: tuple[tuple[float, float, float], ...]
    threshold_profiles: tuple[tuple[float, float], ...]
    event_mix: tuple[EventWeight, ...]
    raw_config_sha256: str
    config_sha256: str
    event_weights_sha256: str

    @property
    def total_weight(self) -> int:
        return sum(item.weight for item in self.event_mix)

    @property
    def derived_runtime_bounds(self) -> dict[str, int]:
        requirement_count = max(self.requirement_count_choices)
        active_chunks = self.document_slots * self.chunks_per_document
        distinct_hashes = len(
            {normalized_text_hash_v1(text) for text in self.text_pool}
        )
        return {
            "active_groups": self.max_active_groups,
            "active_chunks": active_chunks,
            "n_obs": self.max_active_groups * requirement_count * active_chunks,
            "r_max": requirement_count,
            "w_g": requirement_count * active_chunks,
            "e_g": requirement_count * distinct_hashes,
            "h_g": distinct_hashes,
            "reference_matching_leaf_bound": (
                self.max_active_groups * (distinct_hashes + 1) ** requirement_count
            ),
        }


def load_config(path: Path = DEFAULT_CONFIG) -> DifferentialConfig:
    raw_bytes = path.read_bytes()
    raw: object = json.loads(raw_bytes)
    payload = _as_mapping(raw, "config")
    expected_keys = {
        "schema_version",
        "generator_version",
        "prng",
        "seed",
        "committed_events",
        "committed_events_per_stream",
        "max_proposals_per_stream",
        "short_prefix_committed_events",
        "claim_count",
        "document_slots",
        "bootstrap_document_slots",
        "chunks_per_document",
        "family_slots",
        "bootstrap_family_slots",
        "max_active_groups",
        "requirement_count_choices",
        "text_pool",
        "score_profiles",
        "threshold_profiles",
        "event_mix",
    }
    if set(payload) != expected_keys:
        raise ValueError("config keys do not match the frozen schema")
    event_mix: list[EventWeight] = []
    for index, item in enumerate(_as_sequence(payload.get("event_mix"), "event_mix")):
        row = _as_mapping(item, f"event_mix[{index}]")
        if set(row) != {"kind", "weight"}:
            raise ValueError(f"event_mix[{index}] has unexpected keys")
        event_mix.append(
            EventWeight(
                _as_text(row.get("kind"), f"event_mix[{index}].kind"),
                _as_int(row.get("weight"), f"event_mix[{index}].weight", minimum=1),
            )
        )
    if {item.kind for item in event_mix} != PROPOSAL_KINDS:
        raise ValueError(
            "event_mix must contain every frozen proposal kind exactly once"
        )
    if len(event_mix) != len(PROPOSAL_KINDS):
        raise ValueError("event_mix contains a duplicate proposal kind")

    requirement_choices = tuple(
        _as_int(value, "requirement_count_choices[]", minimum=1)
        for value in _as_sequence(
            payload.get("requirement_count_choices"),
            "requirement_count_choices",
        )
    )
    if not requirement_choices or max(requirement_choices) > 8:
        raise ValueError("requirement_count_choices must be nonempty and bounded by 8")
    text_pool = tuple(
        _as_text(value, "text_pool[]")
        for value in _as_sequence(payload.get("text_pool"), "text_pool")
    )
    if not text_pool:
        raise ValueError("text_pool must not be empty")

    score_profiles: list[tuple[float, float, float]] = []
    for index, item in enumerate(
        _as_sequence(payload.get("score_profiles"), "score_profiles")
    ):
        values = _as_sequence(item, f"score_profiles[{index}]")
        if len(values) != 3:
            raise ValueError("each score profile must have exactly three values")
        score_profiles.append(
            (
                _as_float(values[0], "support score"),
                _as_float(values[1], "refute score"),
                _as_float(values[2], "neutral score"),
            )
        )
        if abs(sum(score_profiles[-1]) - 1.0) > 1e-12:
            raise ValueError("each score profile must sum to one")
    threshold_profiles: list[tuple[float, float]] = []
    for index, item in enumerate(
        _as_sequence(payload.get("threshold_profiles"), "threshold_profiles")
    ):
        values = _as_sequence(item, f"threshold_profiles[{index}]")
        if len(values) != 2:
            raise ValueError("each threshold profile must have exactly two values")
        threshold_profiles.append(
            (
                _as_float(values[0], "support threshold"),
                _as_float(values[1], "refute threshold"),
            )
        )
    if not score_profiles or not threshold_profiles:
        raise ValueError("score and threshold profiles must not be empty")

    config = DifferentialConfig(
        schema_version=_as_text(payload.get("schema_version"), "schema_version"),
        generator_version=_as_text(
            payload.get("generator_version"), "generator_version"
        ),
        prng=_as_text(payload.get("prng"), "prng"),
        seed=_as_int(payload.get("seed"), "seed"),
        committed_events=_as_int(
            payload.get("committed_events"), "committed_events", minimum=1
        ),
        committed_events_per_stream=_as_int(
            payload.get("committed_events_per_stream"),
            "committed_events_per_stream",
            minimum=1,
        ),
        max_proposals_per_stream=_as_int(
            payload.get("max_proposals_per_stream"),
            "max_proposals_per_stream",
            minimum=1,
        ),
        short_prefix_committed_events=_as_int(
            payload.get("short_prefix_committed_events"),
            "short_prefix_committed_events",
            minimum=1,
        ),
        claim_count=_as_int(payload.get("claim_count"), "claim_count", minimum=1),
        document_slots=_as_int(
            payload.get("document_slots"), "document_slots", minimum=1
        ),
        bootstrap_document_slots=_as_int(
            payload.get("bootstrap_document_slots"),
            "bootstrap_document_slots",
        ),
        chunks_per_document=_as_int(
            payload.get("chunks_per_document"),
            "chunks_per_document",
            minimum=1,
        ),
        family_slots=_as_int(payload.get("family_slots"), "family_slots", minimum=1),
        bootstrap_family_slots=_as_int(
            payload.get("bootstrap_family_slots"), "bootstrap_family_slots"
        ),
        max_active_groups=_as_int(
            payload.get("max_active_groups"), "max_active_groups", minimum=1
        ),
        requirement_count_choices=requirement_choices,
        text_pool=text_pool,
        score_profiles=tuple(score_profiles),
        threshold_profiles=tuple(threshold_profiles),
        event_mix=tuple(event_mix),
        raw_config_sha256=_sha256(raw_bytes),
        config_sha256=_sha256(_canonical_json_bytes(payload)),
        event_weights_sha256=_sha256(
            _canonical_json_bytes([asdict(item) for item in event_mix])
        ),
    )
    if config.schema_version != CONFIG_SCHEMA:
        raise ValueError(f"unsupported config schema {config.schema_version!r}")
    if config.generator_version != GENERATOR_VERSION:
        raise ValueError(f"unsupported generator {config.generator_version!r}")
    if config.prng != "splitmix64-v1":
        raise ValueError(f"unsupported PRNG {config.prng!r}")
    if config.seed > MASK_64:
        raise ValueError("seed must fit an unsigned 64-bit integer")
    if config.seed != FROZEN_SEED:
        raise ValueError("seed does not match the frozen M5.2 gate")
    if config.committed_events != FROZEN_COMMITTED_EVENTS:
        raise ValueError("committed-event target does not match the frozen M5.2 gate")
    if config.committed_events_per_stream != FROZEN_COMMITS_PER_STREAM:
        raise ValueError("stream size does not match the frozen M5.2 gate")
    if config.short_prefix_committed_events != FROZEN_SHORT_PREFIX:
        raise ValueError("short prefix does not match the frozen M5.2 gate")
    if config.total_weight != 100:
        raise ValueError("frozen event_mix weights must sum to 100")
    if config.bootstrap_document_slots > config.document_slots:
        raise ValueError("bootstrap_document_slots exceeds document_slots")
    if config.bootstrap_family_slots > config.family_slots:
        raise ValueError("bootstrap_family_slots exceeds family_slots")
    if config.max_active_groups > config.family_slots:
        raise ValueError("max_active_groups exceeds family_slots")
    if config.short_prefix_committed_events > config.committed_events:
        raise ValueError("short prefix exceeds the full committed-event target")
    if config.max_proposals_per_stream < config.committed_events_per_stream:
        raise ValueError("max proposals per stream is below the commit target")
    bounds = config.derived_runtime_bounds
    if bounds["r_max"] > 8:
        raise ValueError("derived r_max exceeds the frozen M5 bound")
    if bounds["h_g"] > 16 or bounds["e_g"] > 128:
        raise ValueError("derived group graph bounds exceed frozen audit caps")
    if bounds["reference_matching_leaf_bound"] > 100_000:
        raise ValueError("reference matching bound exceeds the frozen audit cap")
    return config


class SplitMix64:
    """Frozen SplitMix64-v1 integer stream with unbiased bounded selection."""

    __slots__ = ("_state",)

    def __init__(self, seed: int) -> None:
        self._state = seed & MASK_64

    def next_u64(self) -> int:
        self._state = (self._state + 0x9E3779B97F4A7C15) & MASK_64
        value = self._state
        value = ((value ^ (value >> 30)) * 0xBF58476D1CE4E5B9) & MASK_64
        value = ((value ^ (value >> 27)) * 0x94D049BB133111EB) & MASK_64
        return (value ^ (value >> 31)) & MASK_64

    def randbelow(self, upper: int) -> int:
        if upper <= 0:
            raise ValueError("randbelow upper bound must be positive")
        modulus = 1 << 64
        limit = modulus - (modulus % upper)
        while True:
            value = self.next_u64()
            if value < limit:
                return value % upper

    def choose(self, values: Sequence[str]) -> str:
        if not values:
            raise ValueError("cannot choose from an empty sequence")
        return values[self.randbelow(len(values))]


