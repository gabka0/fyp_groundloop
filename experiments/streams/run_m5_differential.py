def frozen_summary(summary: Mapping[str, object]) -> dict[str, object]:
    return {key: summary[key] for key in FROZEN_SUMMARY_KEYS}


def _assert_planned_coverage(summary: Mapping[str, object]) -> None:
    expected_event_types = {
        event_type.__name__
        for event_type in (
            *M5_EVENT_TYPES,
            InsertDocumentEvent,
            DeleteDocumentVersionEvent,
            ReplaceDocumentVersionEvent,
            PolicyChangeEvent,
            ObserveEvent,
        )
    }
    event_counts = _as_mapping(summary.get("event_type_counts"), "event counts")
    proposal_counts = _as_mapping(
        summary.get("proposal_kind_counts"),
        "proposal counts",
    )
    _require(
        set(event_counts) == expected_event_types,
        "planned prefix does not cover every committed event class",
    )
    _require(
        set(proposal_counts) == PROPOSAL_KINDS,
        "planned prefix does not cover every proposal kind",
    )
    _require(
        _as_int(summary.get("exact_replays"), "exact_replays") > 0,
        "planned stream has no replay",
    )
    _require(
        _as_int(
            summary.get("generator_rejections"),
            "generator_rejections",
        )
        > 0,
        "planned stream has no rejection",
    )
    _require(
        _as_int(
            summary.get("duplicate_chunks_generated"),
            "duplicate_chunks_generated",
        )
        > 0,
        "planned stream has no duplicate chunk text",
    )


def load_manifest(
    path: Path = DEFAULT_MANIFEST,
) -> tuple[dict[str, object], str, str]:
    raw_bytes = path.read_bytes()
    raw: object = json.loads(raw_bytes)
    payload = _as_mapping(raw, "manifest")
    return (
        payload,
        _sha256(raw_bytes),
        _sha256(_canonical_json_bytes(payload)),
    )


def verify_manifest_header(
    config: DifferentialConfig,
    manifest: Mapping[str, object],
) -> None:
    expected = {
        "schema_version": MANIFEST_SCHEMA,
        "generator_version": config.generator_version,
        "prng": config.prng,
        "seed": config.seed,
        "raw_config_sha256": config.raw_config_sha256,
        "config_sha256": config.config_sha256,
        "event_weights_sha256": config.event_weights_sha256,
        "runner_sha256": _runner_sha256(),
        "committed_events": config.committed_events,
        "committed_events_per_stream": config.committed_events_per_stream,
        "max_proposals_per_stream": config.max_proposals_per_stream,
        "short_prefix_committed_events": config.short_prefix_committed_events,
        "derived_runtime_bounds": config.derived_runtime_bounds,
    }
    expected_keys = {*expected, "planned_prefix", "planned_full"}
    if set(manifest) != expected_keys:
        raise AssertionError("manifest keys do not match the frozen schema")
    for key, value in expected.items():
        if manifest.get(key) != value:
            raise AssertionError(f"manifest header mismatch for {key}")


def verify_manifest_summary(
    summary: Mapping[str, object],
    manifest: Mapping[str, object],
    section: str,
) -> None:
    expected = _as_mapping(manifest.get(section), f"manifest.{section}")
    actual = frozen_summary(summary)
    if set(expected) != set(FROZEN_SUMMARY_KEYS):
        raise AssertionError(f"manifest {section} keys are not frozen")
    if actual != expected:
        raise AssertionError(
            f"manifest {section} mismatch:\n"
            f"expected={json.dumps(expected, sort_keys=True)}\n"
            f"actual={json.dumps(actual, sort_keys=True)}"
        )


def _write_result(path: Path, result: Mapping[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(dict(result), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--mode", choices=("plan", "prefix", "full"), default="prefix")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()

    config = load_config(args.config)
    if args.mode == "plan":
        prefix = run_randomized_differential(
            config,
            committed_events=config.short_prefix_committed_events,
            validate=False,
        )
        full = run_randomized_differential(
            config,
            committed_events=config.committed_events,
            validate=False,
        )
        _assert_planned_coverage(prefix)
        _assert_planned_coverage(full)
        _require(
            full["short_prefix_checkpoint"] == frozen_summary(prefix),
            "standalone prefix diverges from the full-stream checkpoint",
        )
        result: dict[str, object] = {
            "schema_version": MANIFEST_SCHEMA,
            "generator_version": config.generator_version,
            "prng": config.prng,
            "seed": config.seed,
            "raw_config_sha256": config.raw_config_sha256,
            "config_sha256": config.config_sha256,
            "event_weights_sha256": config.event_weights_sha256,
            "runner_sha256": _runner_sha256(),
            "committed_events": config.committed_events,
            "committed_events_per_stream": config.committed_events_per_stream,
            "max_proposals_per_stream": config.max_proposals_per_stream,
            "short_prefix_committed_events": config.short_prefix_committed_events,
            "derived_runtime_bounds": config.derived_runtime_bounds,
            "planned_prefix": frozen_summary(prefix),
            "planned_full": frozen_summary(full),
        }
    else:
        manifest, manifest_raw_sha256, manifest_canonical_sha256 = load_manifest(
            args.manifest
        )
        verify_manifest_header(config, manifest)
        if args.mode == "prefix":
            target = config.short_prefix_committed_events
            section = "planned_prefix"
        else:
            target = config.committed_events
            section = "planned_full"
        planned = run_randomized_differential(
            config,
            committed_events=target,
            validate=False,
        )
        verify_manifest_summary(planned, manifest, section)
        result = run_randomized_differential(
            config,
            committed_events=target,
            validate=True,
        )
        verify_manifest_summary(result, manifest, section)
        result["manifest_raw_sha256"] = manifest_raw_sha256
        result["manifest_canonical_sha256"] = manifest_canonical_sha256
        result["verified_manifest_section"] = section

    if args.output is not None:
        _write_result(args.output, result)
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
