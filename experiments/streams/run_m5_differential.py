class _StreamGenerator:
    def __init__(
        self,
        config: DifferentialConfig,
        stream_id: int,
        rng: SplitMix64,
    ) -> None:
        self.config = config
        self.stream_id = stream_id
        self.rng = rng
        self.claim_ids = tuple(
            f"s{stream_id}-claim-{index}" for index in range(config.claim_count)
        )
        self.documents = [
            _DocumentCursor(slot=index) for index in range(config.document_slots)
        ]
        self.groups = [
            _GroupCursor(index, self.claim_ids[index % len(self.claim_ids)])
            for index in range(config.family_slots)
        ]
        self.requirement_keys: dict[tuple[str, str], None] = {}
        self.claim_keys: dict[tuple[str, str], None] = {}
        self.committed_events: list[CommittedOverlayEvent] = []
        self.policy_generation = 0
        self.seen_texts: set[str] = set()
        self.duplicate_chunks_generated = 0
        self._install_bootstrap_cursors()

    def shadow_checkpoint(self) -> _GeneratorShadow:
        return _GeneratorShadow(
            documents=tuple(
                _DocumentCursor(
                    slot=cursor.slot,
                    generation=cursor.generation,
                    version_id=cursor.version_id,
                    chunk_ids=cursor.chunk_ids,
                    chunk_texts=cursor.chunk_texts,
                )
                for cursor in self.documents
            ),
            groups=tuple(
                _GroupCursor(
                    slot=cursor.slot,
                    claim_id=cursor.claim_id,
                    generation=cursor.generation,
                    group_id=cursor.group_id,
                    requirement_ids=cursor.requirement_ids,
                    requirement_texts=cursor.requirement_texts,
                    predecessor_ids=cursor.predecessor_ids,
                    retired=cursor.retired,
                )
                for cursor in self.groups
            ),
            requirement_keys=dict(self.requirement_keys),
            claim_keys=dict(self.claim_keys),
            policy_generation=self.policy_generation,
            seen_texts=frozenset(self.seen_texts),
            duplicate_chunks_generated=self.duplicate_chunks_generated,
        )

    def restore_shadow(self, checkpoint: _GeneratorShadow) -> None:
        self.documents = [
            _DocumentCursor(
                slot=cursor.slot,
                generation=cursor.generation,
                version_id=cursor.version_id,
                chunk_ids=cursor.chunk_ids,
                chunk_texts=cursor.chunk_texts,
            )
            for cursor in checkpoint.documents
        ]
        self.groups = [
            _GroupCursor(
                slot=cursor.slot,
                claim_id=cursor.claim_id,
                generation=cursor.generation,
                group_id=cursor.group_id,
                requirement_ids=cursor.requirement_ids,
                requirement_texts=cursor.requirement_texts,
                predecessor_ids=cursor.predecessor_ids,
                retired=cursor.retired,
            )
            for cursor in checkpoint.groups
        ]
        self.requirement_keys = dict(checkpoint.requirement_keys)
        self.claim_keys = dict(checkpoint.claim_keys)
        self.policy_generation = checkpoint.policy_generation
        self.seen_texts = set(checkpoint.seen_texts)
        self.duplicate_chunks_generated = checkpoint.duplicate_chunks_generated

    def _install_bootstrap_cursors(self) -> None:
        for document_cursor in self.documents[: self.config.bootstrap_document_slots]:
            document_cursor.generation = 1
            self._set_document_payload(document_cursor, randomized=False)
        for group_cursor in self.groups[: self.config.bootstrap_family_slots]:
            group_cursor.generation = 1
            count = self.config.requirement_count_choices[
                group_cursor.slot % len(self.config.requirement_count_choices)
            ]
            self._set_group_payload(group_cursor, count, predecessors=())

    def _document_id(self, cursor: _DocumentCursor) -> str:
        return f"s{self.stream_id}-document-{cursor.slot}"

    def _set_document_payload(
        self,
        cursor: _DocumentCursor,
        *,
        randomized: bool,
    ) -> None:
        version_id = f"s{self.stream_id}-document-{cursor.slot}-v{cursor.generation}"
        chunk_ids = tuple(
            f"{version_id}-chunk-{index}"
            for index in range(self.config.chunks_per_document)
        )
        if randomized:
            texts = tuple(
                self.config.text_pool[self.rng.randbelow(len(self.config.text_pool))]
                for _ in chunk_ids
            )
            for text in texts:
                if text in self.seen_texts:
                    self.duplicate_chunks_generated += 1
                self.seen_texts.add(text)
        else:
            texts = tuple(
                self.config.text_pool[
                    (cursor.slot * self.config.chunks_per_document + index)
                    % len(self.config.text_pool)
                ]
                for index in range(len(chunk_ids))
            )
            self.seen_texts.update(texts)
        cursor.version_id = version_id
        cursor.chunk_ids = chunk_ids
        cursor.chunk_texts = texts

    def _set_group_payload(
        self,
        cursor: _GroupCursor,
        requirement_count: int,
        *,
        predecessors: tuple[str, ...],
    ) -> None:
        group_id = f"s{self.stream_id}-family-{cursor.slot}-v{cursor.generation}"
        cursor.group_id = group_id
        cursor.requirement_ids = tuple(
            f"{group_id}-requirement-{ordinal}" for ordinal in range(requirement_count)
        )
        cursor.requirement_texts = tuple(
            (
                f"stream {self.stream_id} family {cursor.slot} generation "
                f"{cursor.generation} requirement {ordinal}"
            )
            for ordinal in range(requirement_count)
        )
        cursor.predecessor_ids = tuple(
            predecessors[ordinal] if ordinal < len(predecessors) else None
            for ordinal in range(requirement_count)
        )

    def _group(self, cursor: _GroupCursor) -> EvidenceGroupVersion:
        group_id = cursor.group_id
        if group_id is None:
            raise AssertionError("active group cursor has no group ID")
        requirements = tuple(
            EvidenceRequirementVersion(
                requirement_version_id=requirement_id,
                group_version_id=group_id,
                ordinal=ordinal,
                requirement_text=cursor.requirement_texts[ordinal],
                supersedes_requirement_version_id=cursor.predecessor_ids[ordinal],
            )
            for ordinal, requirement_id in enumerate(cursor.requirement_ids)
        )
        return EvidenceGroupVersion(
            group_version_id=group_id,
            group_family_id=f"s{self.stream_id}-family-{cursor.slot}",
            owner_claim_id=cursor.claim_id,
            requirements=requirements,
            construction_kind=ConstructionKind.CONTROLLED,
            construction_source_id=GENERATOR_VERSION,
            supersedes_group_version_id=(
                None
                if cursor.generation == 1
                else f"s{self.stream_id}-family-{cursor.slot}-v{cursor.generation - 1}"
            ),
        )

    def fixture_repository(self) -> tuple[M5Repository, int]:
        base = InMemoryRepository()
        apply_event(
            base,
            PolicyChangeEvent(
                event_id=f"s{self.stream_id}-fixture-policy",
                policy=DecisionPolicy(
                    policy_version=f"s{self.stream_id}-policy-0",
                    support_threshold=0.8,
                    refute_threshold=0.8,
                ),
            ),
        )
        question_id = f"s{self.stream_id}-question"
        answer_id = f"s{self.stream_id}-answer"
        base.register_question(Question(question_id, "generated question"))
        base.register_answer(
            AnswerVersion(answer_id, question_id, "generated answer", STAMP),
            tuple(
                Claim(claim_id, answer_id, f"claim {index}", STAMP, True)
                for index, claim_id in enumerate(self.claim_ids)
            ),
        )
        fixture_events = 1
        for document_cursor in self.documents[: self.config.bootstrap_document_slots]:
            version_id = document_cursor.version_id
            if version_id is None:
                raise AssertionError("bootstrap document is inactive")
            apply_event(
                base,
                InsertDocumentEvent(
                    event_id=(
                        f"s{self.stream_id}-fixture-document-{document_cursor.slot}"
                    ),
                    document_id=self._document_id(document_cursor),
                    document_version_id=version_id,
                    content_hash=_sha256(f"fixture:{version_id}"),
                    chunks=tuple(
                        ChunkInput(
                            chunk_id,
                            index,
                            document_cursor.chunk_texts[index],
                        )
                        for index, chunk_id in enumerate(document_cursor.chunk_ids)
                    ),
                ),
            )
            fixture_events += 1
        repository = M5Repository(base)
        for group_cursor in self.groups[: self.config.bootstrap_family_slots]:
            apply_m5_event(
                repository,
                RegisterGroupEvent(
                    event_id=(f"s{self.stream_id}-fixture-group-{group_cursor.slot}"),
                    group=self._group(group_cursor),
                ),
            )
            fixture_events += 1
        return repository, fixture_events

    def choose_proposal_kind(self) -> str:
        ticket = self.rng.randbelow(self.config.total_weight)
        cumulative = 0
        for item in self.config.event_mix:
            cumulative += item.weight
            if ticket < cumulative:
                return item.kind
        raise AssertionError("weighted proposal selection fell through")

    def _active_chunks(self) -> list[str]:
        return sorted(
            [
                chunk_id
                for cursor in self.documents
                if cursor.active
                for chunk_id in cursor.chunk_ids
            ]
        )

    def _active_requirements(self) -> list[str]:
        return sorted(
            [
                requirement_id
                for cursor in self.groups
                if cursor.active
                for requirement_id in cursor.requirement_ids
            ]
        )

    def _reject(self, kind: str, reason: str) -> _Proposal:
        return _Proposal(kind, "generator_rejected", None, reason)

    def _observe_requirement(self, kind: str, event_id: str) -> _Proposal:
        active_requirements = self._active_requirements()
        active_chunks = self._active_chunks()
        if kind.endswith("_new"):
            candidates = [
                (requirement_id, chunk_id)
                for requirement_id in active_requirements
                for chunk_id in active_chunks
                if (requirement_id, chunk_id) not in self.requirement_keys
            ]
        else:
            candidates = [
                (requirement_id, chunk_id)
                for requirement_id in active_requirements
                for chunk_id in active_chunks
                if (requirement_id, chunk_id) in self.requirement_keys
            ]
        if not candidates:
            return self._reject(kind, "no_requirement_observation_candidate")
        requirement_id, chunk_id = candidates[self.rng.randbelow(len(candidates))]
        scores = self.config.score_profiles[
            self.rng.randbelow(len(self.config.score_profiles))
        ]
        observation_id = f"{event_id}-requirement-observation"
        event = ObserveRequirementEvent(
            event_id=event_id,
            observation=SemanticObservation(
                observation_id=observation_id,
                subject_kind=SubjectKind.REQUIREMENT,
                subject_id=requirement_id,
                chunk_version_id=chunk_id,
                task_type="verify_requirement_v1",
                support_score=scores[0],
                refute_score=scores[1],
                neutral_score=scores[2],
                producer=STAMP,
                input_hash=_sha256(f"input:{observation_id}"),
            ),
        )
        self.requirement_keys[(requirement_id, chunk_id)] = None
        return _Proposal(kind, "committed", event)

    def _observe_claim(self, kind: str, event_id: str) -> _Proposal:
        active_chunks = self._active_chunks()
        if kind.endswith("_new"):
            candidates = [
                (claim_id, chunk_id)
                for claim_id in self.claim_ids
                for chunk_id in active_chunks
                if (claim_id, chunk_id) not in self.claim_keys
            ]
        else:
            candidates = [
                (claim_id, chunk_id)
                for claim_id in self.claim_ids
                for chunk_id in active_chunks
                if (claim_id, chunk_id) in self.claim_keys
            ]
        if not candidates:
            return self._reject(kind, "no_claim_observation_candidate")
        claim_id, chunk_id = candidates[self.rng.randbelow(len(candidates))]
        scores = self.config.score_profiles[
            self.rng.randbelow(len(self.config.score_profiles))
        ]
        observation_id = f"{event_id}-claim-observation"
        event = ObserveEvent(
            event_id=event_id,
            observation=SemanticObservation(
                observation_id=observation_id,
                subject_kind=SubjectKind.CLAIM,
                subject_id=claim_id,
                chunk_version_id=chunk_id,
                task_type="verify_claim_v1",
                support_score=scores[0],
                refute_score=scores[1],
                neutral_score=scores[2],
                producer=STAMP,
                input_hash=_sha256(f"input:{observation_id}"),
            ),
        )
        self.claim_keys[(claim_id, chunk_id)] = None
        return _Proposal(kind, "committed", event)

    def _insert_document(self, kind: str, event_id: str) -> _Proposal:
        inactive = [cursor for cursor in self.documents if not cursor.active]
        if not inactive:
            return self._reject(kind, "no_inactive_document_slot")
        cursor = inactive[self.rng.randbelow(len(inactive))]
        cursor.generation += 1
        self._set_document_payload(cursor, randomized=True)
        version_id = cursor.version_id
        if version_id is None:
            raise AssertionError("new document payload is inactive")
        return _Proposal(
            kind,
            "committed",
            InsertDocumentEvent(
                event_id=event_id,
                document_id=self._document_id(cursor),
                document_version_id=version_id,
                content_hash=_sha256(f"content:{version_id}:{cursor.chunk_texts!r}"),
                chunks=tuple(
                    ChunkInput(chunk_id, index, cursor.chunk_texts[index])
                    for index, chunk_id in enumerate(cursor.chunk_ids)
                ),
            ),
        )

    def _delete_document(self, kind: str, event_id: str) -> _Proposal:
        active = [cursor for cursor in self.documents if cursor.active]
        if not active:
            return self._reject(kind, "no_active_document")
        cursor = active[self.rng.randbelow(len(active))]
        version_id = cursor.version_id
        if version_id is None:
            raise AssertionError("active document has no version")
        event = DeleteDocumentVersionEvent(event_id, version_id)
        cursor.version_id = None
        cursor.chunk_ids = ()
        cursor.chunk_texts = ()
        return _Proposal(kind, "committed", event)

    def _replace_document(self, kind: str, event_id: str) -> _Proposal:
        active = [cursor for cursor in self.documents if cursor.active]
        if not active:
            return self._reject(kind, "no_active_document")
        cursor = active[self.rng.randbelow(len(active))]
        old_version_id = cursor.version_id
        if old_version_id is None:
            raise AssertionError("active document has no version")
        cursor.generation += 1
        self._set_document_payload(cursor, randomized=True)
        new_version_id = cursor.version_id
        if new_version_id is None:
            raise AssertionError("replacement document payload is inactive")
        return _Proposal(
            kind,
            "committed",
            ReplaceDocumentVersionEvent(
                event_id=event_id,
                document_id=self._document_id(cursor),
                old_document_version_id=old_version_id,
                new_document_version_id=new_version_id,
                content_hash=_sha256(
                    f"content:{new_version_id}:{cursor.chunk_texts!r}"
                ),
                chunks=tuple(
                    ChunkInput(chunk_id, index, cursor.chunk_texts[index])
                    for index, chunk_id in enumerate(cursor.chunk_ids)
                ),
            ),
        )

    def _policy_change(self, kind: str, event_id: str) -> _Proposal:
        self.policy_generation += 1
        thresholds = self.config.threshold_profiles[
            self.rng.randbelow(len(self.config.threshold_profiles))
        ]
        return _Proposal(
            kind,
            "committed",
            PolicyChangeEvent(
                event_id=event_id,
                policy=DecisionPolicy(
                    policy_version=(
                        f"s{self.stream_id}-policy-{self.policy_generation}"
                    ),
                    support_threshold=thresholds[0],
                    refute_threshold=thresholds[1],
                ),
            ),
        )

    def _register_group(self, kind: str, event_id: str) -> _Proposal:
        active_count = sum(cursor.active for cursor in self.groups)
        available = [
            cursor
            for cursor in self.groups
            if cursor.generation == 0 and not cursor.retired
        ]
        if active_count >= self.config.max_active_groups:
            return self._reject(kind, "max_active_groups_reached")
        if not available:
            return self._reject(kind, "no_unused_group_family")
        cursor = available[self.rng.randbelow(len(available))]
        cursor.generation = 1
        count = self.config.requirement_count_choices[
            self.rng.randbelow(len(self.config.requirement_count_choices))
        ]
        self._set_group_payload(cursor, count, predecessors=())
        return _Proposal(
            kind,
            "committed",
            RegisterGroupEvent(event_id=event_id, group=self._group(cursor)),
        )

    def _replace_group(self, kind: str, event_id: str) -> _Proposal:
        active = [cursor for cursor in self.groups if cursor.active]
        if not active:
            return self._reject(kind, "no_active_group")
        cursor = active[self.rng.randbelow(len(active))]
        old_group_id = cursor.group_id
        if old_group_id is None:
            raise AssertionError("active group has no group ID")
        predecessors = cursor.requirement_ids
        cursor.generation += 1
        count = self.config.requirement_count_choices[
            self.rng.randbelow(len(self.config.requirement_count_choices))
        ]
        self._set_group_payload(cursor, count, predecessors=predecessors)
        return _Proposal(
            kind,
            "committed",
            ReplaceGroupEvent(
                event_id=event_id,
                old_group_version_id=old_group_id,
                successor=self._group(cursor),
            ),
        )

    def _retire_group(self, kind: str, event_id: str) -> _Proposal:
        active = [cursor for cursor in self.groups if cursor.active]
        if not active:
            return self._reject(kind, "no_active_group")
        cursor = active[self.rng.randbelow(len(active))]
        group_id = cursor.group_id
        if group_id is None:
            raise AssertionError("active group has no group ID")
        event = RetireGroupEvent(event_id=event_id, group_version_id=group_id)
        cursor.group_id = None
        cursor.requirement_ids = ()
        cursor.requirement_texts = ()
        cursor.predecessor_ids = ()
        cursor.retired = True
        return _Proposal(kind, "committed", event)

    def propose(self, kind: str, event_id: str) -> _Proposal:
        if kind == "observe_requirement_new" or kind == (
            "observe_requirement_supersede"
        ):
            return self._observe_requirement(kind, event_id)
        if kind == "observe_claim_new" or kind == "observe_claim_supersede":
            return self._observe_claim(kind, event_id)
        if kind == "insert_document":
            return self._insert_document(kind, event_id)
        if kind == "delete_document":
            return self._delete_document(kind, event_id)
        if kind == "replace_document":
            return self._replace_document(kind, event_id)
        if kind == "policy_change":
            return self._policy_change(kind, event_id)
        if kind == "register_group":
            return self._register_group(kind, event_id)
        if kind == "replace_group":
            return self._replace_group(kind, event_id)
        if kind == "retire_group":
            return self._retire_group(kind, event_id)
        if kind == "exact_replay":
            if not self.committed_events:
                return self._reject(kind, "no_committed_event_to_replay")
            event = self.committed_events[
                self.rng.randbelow(len(self.committed_events))
            ]
            return _Proposal(kind, "exact_replay", event)
        if kind == "generator_rejection":
            return self._reject(kind, "scheduled_generator_rejection")
        raise AssertionError(f"unknown proposal kind {kind!r}")

    def record_committed(self, event: CommittedOverlayEvent) -> None:
        self.committed_events.append(event)


